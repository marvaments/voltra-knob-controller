#!/usr/bin/env python3
"""Regenerates src/bootlogo.h from assets/liftlayered_logo_source.png.

Run this again if the LiftLayered logo art ever changes:

    python3 tools/convert_bootlogo.py

What it does:
  1. Finds the tight bounding box of the actual logo ink (the stacked-bar
     mark + "L L" wordmark) inside the source image, ignoring its cream
     background -- the source PNG has a lot of empty padding around the
     mark itself.
  2. Crops to that box (plus a small pad so anti-aliased edges aren't cut
     off) and downscales it to fit within kTargetMaxDim pixels on its
     longest side.
  3. Converts every pixel to RGB565 (same 16-bit format the display and
     the rest of this firmware's UI use -- see ui.cpp's RGB565() calls)
     and writes it out as a plain C array.

Deliberately embeds only the small cropped logo bitmap, not a full
360x360 frame -- bootscreen.cpp fills the screen with the logo's own
background color (kBgColor565, sampled from the source image) first via a
cheap fillScreen(), then blits just this much smaller bitmap on top. That
keeps the generated header well under half the size a full-frame bitmap
would be, for the same on-screen result.

Requires Pillow (`pip install pillow`); not part of the firmware build
itself, so this dependency doesn't affect the PlatformIO build at all.
"""
import argparse
import os
from PIL import Image

DEFAULT_SRC = os.path.join(os.path.dirname(__file__), "..", "assets", "liftlayered_logo_source.png")
DEFAULT_DST = os.path.join(os.path.dirname(__file__), "..", "src", "bootlogo.h")


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--src", default=DEFAULT_SRC, help="source logo PNG (default: assets/liftlayered_logo_source.png)")
    ap.add_argument("--dst", default=DEFAULT_DST, help="output header path (default: src/bootlogo.h)")
    ap.add_argument("--target-max-dim", type=int, default=230,
                     help="longest side of the final embedded bitmap, in pixels (default: 230 -- "
                          "comfortably inside this board's ~172px round-safe radius; see ui.cpp's kSafeR)")
    ap.add_argument("--bg-tolerance", type=int, default=10,
                     help="per-pixel sum-of-channel-differences threshold for \"this pixel is background, "
                          "not logo ink\" when finding the crop box (default: 10)")
    ap.add_argument("--pad", type=int, default=6, help="extra pixels kept around the detected ink bbox before cropping")
    args = ap.parse_args()

    img = Image.open(args.src).convert("RGB")
    w, h = img.size
    px = img.load()
    bg = px[0, 0]  # corner pixel -- reliably background on this source image

    def diff(a, b):
        return abs(a[0] - b[0]) + abs(a[1] - b[1]) + abs(a[2] - b[2])

    minx, miny, maxx, maxy = w, h, -1, -1
    for y in range(h):
        for x in range(w):
            if diff(px[x, y], bg) > args.bg_tolerance:
                minx, miny = min(minx, x), min(miny, y)
                maxx, maxy = max(maxx, x), max(maxy, y)
    if maxx < 0:
        raise SystemExit("no logo ink found -- is --bg-tolerance too high, or is the source image blank?")

    minx = max(0, minx - args.pad)
    miny = max(0, miny - args.pad)
    maxx = min(w - 1, maxx + args.pad)
    maxy = min(h - 1, maxy + args.pad)
    crop = img.crop((minx, miny, maxx + 1, maxy + 1))
    cw, ch = crop.size

    scale = args.target_max_dim / max(cw, ch)
    new_w, new_h = max(1, round(cw * scale)), max(1, round(ch * scale))
    resized = crop.resize((new_w, new_h), Image.LANCZOS)
    rpx = resized.load()

    data = [rgb565(*rpx[x, y]) for y in range(new_h) for x in range(new_w)]
    bg565 = rgb565(*bg)

    with open(args.dst, "w") as f:
        f.write("#pragma once\n#include <cstdint>\n\n")
        f.write("// Auto-generated by tools/convert_bootlogo.py from assets/liftlayered_logo_source.png\n")
        f.write("// -- LiftLayered's brand mark (the same logo used on the company's product\n")
        f.write("// packaging/insert cards), shown as this knob's boot splash. Re-run that\n")
        f.write("// script (do not hand-edit this file) if the logo art ever changes.\n")
        f.write("namespace bootlogo {\n\n")
        f.write(f"constexpr int16_t kWidth = {new_w};\n")
        f.write(f"constexpr int16_t kHeight = {new_h};\n")
        f.write(f"constexpr uint16_t kBgColor565 = 0x{bg565:04X}; // the logo art's own cream background\n\n")
        f.write("// Plain RGB565, row-major, top-to-bottom/left-to-right -- ESP32's flash is\n")
        f.write("// memory-mapped, so this is read directly like any other const array (no\n")
        f.write("// pgm_read_* accessors needed, unlike AVR).\n")
        f.write("static const uint16_t kBitmap[] = {\n")
        line = []
        for v in data:
            line.append(f"0x{v:04X}")
            if len(line) == 16:
                f.write("  " + ",".join(line) + ",\n")
                line = []
        if line:
            f.write("  " + ",".join(line) + ",\n")
        f.write("};\n\n} // namespace bootlogo\n")

    print(f"wrote {args.dst}: {new_w}x{new_h}, {len(data) * 2} bytes of bitmap data")


if __name__ == "__main__":
    main()
